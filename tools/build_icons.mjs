const paths = {};
const emoji = {};
for (const [name, file, ...ems] of ICONS) {
  const svg = readFileSync(join(PKG, 'assets/fill', `${file}-fill.svg`), 'utf8');
  if (!svg.includes('viewBox="0 0 256 256"')) throw new Error(`${file}: unexpected viewBox`);
  const ds = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
  if (!ds.length || /<(circle|rect|line|polygon|polyline|ellipse)\b/.test(svg)) throw new Error(`${file}: not a pure-path icon`);
  paths[name] = ds.join('');
  for (const e of ems) emoji[e] = name;
}

const out = `// GENERATED by tools/build_icons.mjs — do not edit by hand.
// Icon paths: Phosphor Icons "fill" weight, MIT License, © Phosphor Icons (https://phosphoricons.com).
// viewBox 0 0 256 256.

export const ICON_PATHS = ${JSON.stringify(paths, null, 2)} as const;

export type IconName = keyof typeof ICON_PATHS;

/** Emoji (without the U+FE0F variation selector) → the icon drawn in its place. */
export const EMOJI_ICONS: Readonly<Record<string, IconName>> = ${JSON.stringify(emoji, null, 2)};
`;
